export const DICTS: Record<Lang, Dict> = { es, en, pt };
export type { Dict };

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: Dict };
const LangContext = createContext<Ctx>({ lang: "es", setLang: () => {}, t: es });

const esLang = (v: unknown): v is Lang => v === "es" || v === "en" || v === "pt";

export function LangProvider({ children }: { children: React.ReactNode }) {
  // Arranca en es (servidor y primer render del cliente) para no romper la hidratación.
  const [lang, setLangState] = useState<Lang>("es");
  setLocale(LOCALES[lang]);

  useEffect(() => {
    let guardado: string | null = null;
    try {
      guardado = localStorage.getItem(KEY);
    } catch {}
    const nav = typeof navigator !== "undefined" ? navigator.language.slice(0, 2).toLowerCase() : "";
    const inicial = esLang(guardado) ? guardado : esLang(nav) ? nav : "es";
    if (inicial !== "es") setLangState(inicial);
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
    document.title = DICTS[lang].titulo;
  }, [lang]);

  const value = useMemo<Ctx>(
    () => ({
      lang,
      t: DICTS[lang],
      setLang: (l) => {
        setLangState(l);
        try {
          localStorage.setItem(KEY, l);
        } catch {}
      },
    }),
    [lang],
  );
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useT() {
  return useContext(LangContext);
}

/** Selector ES · EN · PT. `tono="oscuro"` para el fondo del amanecer, `"claro"` para páginas claras. */
export function SelectorIdioma({ tono = "oscuro", className = "" }: { tono?: "oscuro" | "claro"; className?: string }) {
  const { lang, setLang, t } = useT();
  const oscuro = tono === "oscuro";
  return (
    <div role="group" aria-label={t.idioma} className={`inline-flex shrink-0 items-center rounded-full border p-0.5 ${oscuro ? "border-white/25 bg-white/8" : "border-line bg-paper"} ${className}`}>
      {LANGS.map((l) => (
        <button
          key={l}
          type="button"
          aria-pressed={lang === l}
          onClick={() => setLang(l)}
          className={`rounded-full px-2 py-1 text-[11px] font-bold tracking-[0.5px] uppercase transition-colors sm:px-2.5 sm:text-[12px] ${
            lang === l ? (oscuro ? "bg-sun text-navy-deep" : "bg-navy text-white") : oscuro ? "text-lavender-soft hover:text-white" : "text-ink-2 hover:text-navy"
          }`}
        >
          {l}
        </button>
      ))}
    </div>
  );
}
